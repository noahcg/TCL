import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { createAdminServer } from '../../src/admin/server.mjs';
import { readFeature } from '../../src/build/homepage-feature.mjs';
test('homepage API authenticates, rejects stale settings and restores failed builds', async t => {
  const root = await mkdtemp(join(tmpdir(), 'tcl-home-'));
  await mkdir(join(root, 'content'));
  const config = await readFeature();
  await writeFile(join(root, 'content/homepage-feature.json'), JSON.stringify(config));
  let fail = false;
  const server = await createAdminServer({ root, inventoryLoader: async () => [{ type: 'article', slug: 'subgrid', title: 'Subgrid', path: '/articles/subgrid/' }], homepageBuilder: async () => { if (fail) throw new Error('build'); } });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await rm(root, { recursive: true, force: true }); });
  const origin = `http://127.0.0.1:${server.address().port}`;
  const html = await (await fetch(origin + '/admin/')).text();
  const token = /name="studio-session" content="([a-f0-9]+)"/.exec(html)[1];
  const url = origin + '/admin/api/homepage-feature';
  assert.equal((await fetch(url)).status, 403);
  const send = (value, expected) => fetch(url, { method: 'POST', headers: { 'X-Admin-Token': token, 'Content-Type': 'application/json' }, body: JSON.stringify({ config: value, expected }) });
  const changed = { ...config, mode: 'manual', pinned: 'aspect-ratio' };
  assert.equal((await send(changed, config)).status, 200);
  assert.equal((await send(config, config)).status, 400);
  fail = true;
  assert.equal((await send(config, changed)).status, 400);
  assert.equal((await readFeature(root)).pinned, 'aspect-ratio');
  fail = false;
  const action = body => fetch(url, { method: 'POST', headers: { 'X-Admin-Token': token, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  let response = await action({ expected: changed, activate: 'fluid-type' });
  assert.equal(response.status, 200);
  let saved = (await response.json()).config;
  assert.equal(saved.pinned, 'fluid-type');
  assert.equal(saved.mode, 'manual');
  assert.ok(saved.usedDemos.includes('fluid-type'));
  response = await action({ expected: saved, demonstratedArticle: 'subgrid' });
  assert.equal(response.status, 200);
  saved = (await response.json()).config;
  assert.ok(saved.usedArticles.includes('subgrid'));
  assert.equal((await send({ ...saved, usedArticles: [], usedDemos: [] }, saved)).status, 200);
  assert.ok((await readFeature(root)).usedArticles.includes('subgrid'));
  assert.ok((await readFeature(root)).usedDemos.includes('fluid-type'));
  response = await action({ expected: await readFeature(root), activate: 'not-implemented' });
  assert.equal(response.status, 400);
});
